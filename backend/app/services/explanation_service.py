import os
import hashlib
import logging
from typing import Optional, Tuple, Dict
from app.core.config import settings

logger = logging.getLogger("cognitrace.quiz.explanation")


class ExplanationService:
    """
    AI Explanation Service for Post-Answer Learning.
    Generates targeted educational explanations after answer submission.
    Guarantees:
    1. Correctness is determined by trusted backend Question Bank, NEVER by the AI.
    2. AI failure never breaks quiz submission (graceful fallback).
    3. In-memory caching for repeat questions.
    """

    _cache: Dict[str, str] = {}

    @classmethod
    def _compute_cache_key(
        cls,
        question_text: str,
        student_answer: str,
        correct_answer: str,
        is_correct: bool
    ) -> str:
        raw_key = f"{question_text.strip().lower()}||{student_answer.strip().lower()}||{correct_answer.strip().lower()}||{is_correct}"
        return hashlib.sha256(raw_key.encode("utf-8")).hexdigest()

    @classmethod
    async def generate_explanation(
        cls,
        question_text: str,
        student_answer: str,
        correct_answer: str,
        concept_name: str,
        is_correct: bool,
        existing_explanation: Optional[str] = None
    ) -> Tuple[Optional[str], str]:
        """
        Generate educational explanation for student answer.
        Returns (explanation_text, explanation_status) where status is:
        - "available" (freshly generated by AI)
        - "cached" (served from cache or Question Bank metadata)
        - "unavailable" (AI failed and no explanation exists)
        """
        cache_key = cls._compute_cache_key(question_text, student_answer, correct_answer, is_correct)

        # 1. Check in-memory cache
        if cache_key in cls._cache:
            return cls._cache[cache_key], "cached"

        # 2. Check API configuration
        api_key = settings.GEMINI_API_KEY
        if not api_key:
            logger.info("[EXPLANATION SERVICE] GEMINI_API_KEY not configured. Using Question Bank explanation.")
            if existing_explanation:
                return existing_explanation, "cached"
            return None, "unavailable"

        # 3. Call Google Gemini to generate educational explanation
        try:
            from google import genai
            from google.genai import types

            client = genai.Client(api_key=api_key)
            model_name = settings.GEMINI_MODEL or "gemini-2.5-flash"

            if is_correct:
                prompt = (
                    f"You are a computer science tutor. The student answered the following question correctly.\n\n"
                    f"Question: {question_text}\n"
                    f"Concept: {concept_name}\n"
                    f"Student's Answer (Correct): {student_answer}\n\n"
                    f"Instructions:\n"
                    f"1. In 2-3 concise sentences, explain WHY this answer is correct and reinforce the core principle of {concept_name}.\n"
                    f"2. Keep it motivating, educational, and precise. Avoid unnecessary fluff."
                )
            else:
                prompt = (
                    f"You are a computer science tutor. The student answered the following question incorrectly.\n\n"
                    f"Question: {question_text}\n"
                    f"Concept: {concept_name}\n"
                    f"Student's Selected Answer (Incorrect): {student_answer}\n"
                    f"Correct Answer: {correct_answer}\n\n"
                    f"Instructions:\n"
                    f"1. State clearly why '{correct_answer}' is the correct choice.\n"
                    f"2. Explain why the student's selection '{student_answer}' is incorrect in this context.\n"
                    f"3. Highlight the core concept of {concept_name} to revise in 2-4 clear sentences."
                )

            response = client.models.generate_content(
                model=model_name,
                contents=prompt,
                config=types.GenerateContentConfig(
                    temperature=0.3,
                    max_output_tokens=300
                )
            )

            explanation_text = response.text.strip() if response and response.text else None

            if explanation_text:
                cls._cache[cache_key] = explanation_text
                return explanation_text, "available"

        except Exception as err:
            logger.warning("[EXPLANATION SERVICE] AI explanation generation failed: %s. Using fallback.", err)

        # 4. Fallback if AI provider call fails or returns empty
        if existing_explanation:
            return existing_explanation, "cached"

        return None, "unavailable"
